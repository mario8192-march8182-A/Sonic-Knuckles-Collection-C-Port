unsigned long random(void) {
  unsigned long wk = g_ram.ranum;
  if (wk == 0) {
    wk = g_sonic3_alone ? 0x2A6D365A : 0x2A6D365B;
  }
  wk *= 41;
  unsigned long wk2 = ((wk & 0x0000FFFF) << 16) + (wk & 0xFFFF0000);
  wk = wk2 & 0xFFFF0000 | wk & 0x0000FFFF;
  g_ram.ranum = wk;
  return g_ram.ranum;
}


